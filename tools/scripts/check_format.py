#!/usr/bin/env python3
"""@package check_format
Check (or fix) the formatting of the Ruby and JSON files a change touches.

Usage: python3 -I tools/scripts/check_format.py [--fix] [--staged | --base REF | --all | FILES...]

  --staged     check what is staged for the next commit (used by the
               .githooks/pre-commit hook). Reads the staged contents, not the
               working tree.
  --base REF   check the files changed since REF (its merge base with HEAD),
               including uncommitted changes. Used by CI and `make check-format`.
  --all        check every tracked Ruby and JSON file.
  FILES        check these files (every line counts as changed).
  --fix        rewrite the files instead of only reporting (not with --staged).
  --allow-missing-rubocop
               only warn, instead of failing, when RuboCop isn't installed.

What is checked:

  JSON   Every *.json file (and Tiled's .tmj/.tsj/.tx/.world/.tiled-project
         files) must be valid JSON; src/mkxp.json may hold // comments. JSON
         that the repository's own tools write must be laid out exactly as
         they write it, so formatting never fights the tools:
           src/pbs/**/*.json    tools/importer/pbs   (pbsjson.store.dumps)
           src/tiled/**/*.json  tools/importer/tiled (tiledc.tiledio.dumps)
         Other JSON is only checked for validity.

  Ruby   RuboCop's Layout cops (with .rubocop.yml), plus syntax errors. Only
         offenses on lines the change adds or edits are reported, so touching
         an older file doesn't mean reformatting all of it. --fix applies
         RuboCop's corrections to those lines only.

lib/ (vendored mkxp-z, Eevee, Essentials) and src/tiled/**/*.rb (event scripts
generated by tools/importer/tiled) are skipped.

RuboCop is run as `bundle exec rubocop` when Bundler is available (see the
Gemfile), else as `rubocop`; set RUBOCOP to override, e.g. RUBOCOP="rubocop".
"""

import argparse
import difflib
import json
import os
import re
import shlex
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path[:0] = [os.path.join(ROOT, "tools", "importer", "pbs"),
                os.path.join(ROOT, "tools", "importer", "tiled")]

from pbsjson import store as pbs_store  # noqa: E402
from tiledc import tiledio  # noqa: E402

## File extensions holding JSON.
JSON_EXTS = (".json", ".tmj", ".tsj", ".tx", ".world", ".tiled-project")
## JSON files that may contain // and /* */ comments (mkxp-z reads them so).
JSONC_FILES = {"src/mkxp.json"}
## Path prefixes that are never checked.
SKIP_PREFIXES = ("lib/",)
## Ruby files under these prefixes are generated and never checked.
RUBY_SKIP_PREFIXES = ("src/tiled/",)
## The RuboCop departments/cops that count as formatting.
RUBOCOP_ONLY = "Layout"
## Marks "every line of this file counts as changed".
ALL_LINES = None


#===============================================================================
# Collecting files and changed lines
#===============================================================================
def git(*args, cwd=ROOT):
    """Runs git and returns its standard output.

    @param args the git arguments
    @return the output as text
    @throws subprocess.CalledProcessError if git fails
    """
    return subprocess.run(["git", "-c", "core.quotepath=off", *args], cwd=cwd, check=True,
                          stdout=subprocess.PIPE, text=True, encoding="utf-8").stdout


def is_ruby(path):
    """True if a path is a Ruby file that should be checked."""
    return path.endswith(".rb") and not path.startswith(SKIP_PREFIXES + RUBY_SKIP_PREFIXES)


def is_json(path):
    """True if a path is a JSON file that should be checked."""
    return path.endswith(JSON_EXTS) and not path.startswith(SKIP_PREFIXES)


def wanted(path):
    """True if a path should be checked at all."""
    return is_ruby(path) or is_json(path)


_HUNK = re.compile(r"^@@ -\d+(?:,\d+)? \+(\d+)(?:,(\d+))? @@")


def parse_diff(text):
    """Reads the files and added/changed lines of a `git diff -U0` output.

    @param text the diff text
    @return a dict of path => set of 1-based line numbers in the new file
    """
    changed = {}
    current = None
    for line in text.splitlines():
        if line.startswith("+++ "):
            name = line[4:].rstrip("\t")
            current = name[2:] if name.startswith("b/") else None
            if current is not None:
                changed.setdefault(current, set())
            continue
        m = _HUNK.match(line)
        if m and current is not None:
            start, count = int(m.group(1)), int(m.group(2) or "1")
            changed[current].update(range(start, start + count))
    return changed


def changed_lines(diff_args):
    """The changed Ruby/JSON files of a diff and their changed lines.

    @param diff_args the arguments that select the diff (e.g. ["--cached"])
    @return a dict of path => set of changed line numbers
    """
    text = git("diff", "--no-ext-diff", "--no-color", "-U0", "--no-renames", "--diff-filter=AM", *diff_args)
    return {path: lines for path, lines in parse_diff(text).items() if wanted(path)}


#===============================================================================
# JSON
#===============================================================================
def strip_json_comments(text):
    """Removes // and /* */ comments that are outside strings.

    @param text JSON text with comments
    @return the text without them (line breaks are kept, so line numbers stay)
    """
    out = []
    i, n = 0, len(text)
    in_string = False
    while i < n:
        c = text[i]
        if in_string:
            out.append(c)
            if c == "\\" and i + 1 < n:
                out.append(text[i + 1])
                i += 1
            elif c == '"':
                in_string = False
        elif c == '"':
            in_string = True
            out.append(c)
        elif text.startswith("//", i):
            while i < n and text[i] != "\n":
                i += 1
            continue
        elif text.startswith("/*", i):
            end = text.find("*/", i + 2)
            end = n if end < 0 else end + 2
            out.append("\n" * text.count("\n", i, end))
            i = end
            continue
        else:
            out.append(c)
        i += 1
    return "".join(out)


def canonical_json(path, value):
    """The text the repository's tools would write for a JSON file.

    @param path the file's path relative to the repository root
    @param value the parsed JSON
    @return the expected text, or None if any valid layout is fine
    """
    if not path.endswith(".json"):
        return None
    if path.startswith("src/pbs/"):
        return pbs_store.dumps(value) + "\n"
    if path.startswith("src/tiled/"):
        return tiledio.dumps(value)
    return None


def check_json(path, text):
    """Checks one JSON file.

    @param path the file's path relative to the repository root
    @param text the file's contents
    @return (problem message or None, the fixed text or None)
    """
    try:
        value = json.loads(strip_json_comments(text) if path in JSONC_FILES else text)
    except json.JSONDecodeError as e:
        return "%s:%d:%d: invalid JSON: %s" % (path, e.lineno, e.colno, e.msg), None
    expected = canonical_json(path, value)
    if expected is None or expected == text:
        return None, None
    diff = difflib.unified_diff(text.splitlines(True), expected.splitlines(True),
                                "a/" + path, "b/" + path, n=1)
    shown = [line if line.endswith("\n") else line + "\n" for line in diff]
    if len(shown) > 60:
        shown = shown[:60] + ["... (%d more diff lines)\n" % (len(shown) - 60)]
    return "%s: not in the layout the repository's tools write:\n%s" % (path, "".join(shown)), expected


#===============================================================================
# Ruby
#===============================================================================
def rubocop_command():
    """The command that runs RuboCop, or None if it isn't installed.

    @return a list of arguments, or None
    """
    if os.environ.get("RUBOCOP"):
        return shlex.split(os.environ["RUBOCOP"])
    gemfile = os.path.join(ROOT, "Gemfile")
    if shutil.which("bundle") and os.path.isfile(gemfile):
        with open(gemfile, encoding="utf-8") as f:
            if re.search(r"""^\s*gem\s+["']rubocop["']""", f.read(), re.M):
                probe = subprocess.run(["bundle", "exec", "rubocop", "--version"], cwd=ROOT,
                                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
                if probe.returncode == 0:
                    return ["bundle", "exec", "rubocop"]
    if shutil.which("rubocop"):
        return ["rubocop"]
    return None


def run_rubocop(rubocop, files, cwd, autocorrect=False):
    """Runs RuboCop's formatting cops on some files.

    @param rubocop the command from rubocop_command()
    @param files paths relative to cwd
    @param cwd the folder the paths are relative to
    @param autocorrect whether to apply safe corrections in place
    @return a dict of path => list of offenses (RuboCop's JSON offense objects)
    """
    cmd = rubocop + ["--config", os.path.join(ROOT, ".rubocop.yml"), "--only", RUBOCOP_ONLY,
                     "--format", "json"]
    if autocorrect:
        cmd.append("--autocorrect")
    proc = subprocess.run(cmd + ["--"] + files, cwd=cwd, stdout=subprocess.PIPE,
                          stderr=subprocess.PIPE, text=True, encoding="utf-8",
                          env=dict(os.environ, BUNDLE_GEMFILE=os.path.join(ROOT, "Gemfile")))
    if proc.returncode not in (0, 1):
        sys.stderr.write(proc.stderr)
        raise RuntimeError("RuboCop failed (exit code %d)" % proc.returncode)
    report = json.loads(proc.stdout)
    return {f["path"]: f["offenses"] for f in report["files"]}


def offense_lines(offense):
    """The lines an offense covers.

    @param offense a RuboCop JSON offense
    @return a range of 1-based line numbers
    """
    loc = offense["location"]
    first = loc.get("start_line", loc.get("line", 1))
    return range(first, loc.get("last_line", first) + 1)


def relevant(offense, lines):
    """True if an offense touches a changed line (syntax errors always count).

    @param offense a RuboCop JSON offense
    @param lines the changed lines, or ALL_LINES
    """
    if lines is ALL_LINES or offense["cop_name"] == "Lint/Syntax":
        return True
    return any(n in lines for n in offense_lines(offense))


def merge_fixes(original, corrected, lines):
    """Applies only the corrections that touch changed lines.

    @param original the file's text
    @param corrected the file's text after RuboCop's corrections
    @param lines the changed lines, or ALL_LINES
    @return the merged text
    """
    if lines is ALL_LINES:
        return corrected
    a, b = original.splitlines(True), corrected.splitlines(True)
    out = []
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(None, a, b, autojunk=False).get_opcodes():
        if tag == "replace" and i2 - i1 == j2 - j1:
            # Same number of lines: take each corrected line on its own.
            for k in range(i2 - i1):
                out.append(b[j1 + k] if i1 + k + 1 in lines else a[i1 + k])
            continue
        touched = range(i1 + 1, i2 + 1) if i2 > i1 else (i1, i1 + 1)
        if tag != "equal" and any(n in lines for n in touched):
            out.extend(b[j1:j2])
        else:
            out.extend(a[i1:i2])
    return "".join(out)


def format_offense(path, offense):
    """One line describing an offense, like RuboCop's own output."""
    loc = offense["location"]
    mark = " [Correctable]" if offense.get("correctable") else ""
    return "%s:%d:%d: %s: %s%s" % (path, loc.get("start_line", loc.get("line", 1)),
                                    loc.get("start_column", loc.get("column", 1)),
                                    offense["cop_name"], offense["message"], mark)


#===============================================================================
# Main
#===============================================================================
def read(base, path):
    """Reads a file below a folder as UTF-8 text (with its line endings)."""
    with open(os.path.join(base, path), encoding="utf-8", newline="") as f:
        return f.read()


def write(path, text):
    """Writes a file below the repository root as UTF-8 text."""
    with open(os.path.join(ROOT, path), "w", encoding="utf-8", newline="") as f:
        f.write(text)


def collect(args):
    """The files to check and their changed lines, for the chosen mode.

    @param args the parsed command line
    @return a dict of path => set of changed lines (or ALL_LINES)
    """
    if args.staged:
        return changed_lines(["--cached"])
    if args.base:
        base = git("merge-base", args.base, "HEAD").strip()
        return changed_lines([base])
    if args.all:
        files = git("ls-files", "-z").split("\0")
        return {path: ALL_LINES for path in files if path and wanted(path)}
    files = {}
    for name in args.files:
        path = os.path.relpath(os.path.abspath(name), ROOT).replace(os.sep, "/")
        if wanted(path):
            files[path] = ALL_LINES
    return files


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--staged", action="store_true", help="check the staged changes")
    mode.add_argument("--base", metavar="REF", help="check the changes since REF")
    mode.add_argument("--all", action="store_true", help="check every tracked file")
    parser.add_argument("--fix", action="store_true", help="fix the files instead of only reporting")
    parser.add_argument("--allow-missing-rubocop", action="store_true",
                        help="only warn when RuboCop isn't installed")
    parser.add_argument("files", nargs="*", help="files to check")
    args = parser.parse_args(argv)
    if args.files and (args.staged or args.base or args.all):
        parser.error("give either files or --staged/--base/--all")
    if not args.files and not (args.staged or args.base or args.all):
        parser.error("give files, --staged, --base REF or --all")
    if args.fix and args.staged:
        parser.error("--fix can't be used with --staged; run `make format` instead")

    files = collect(args)
    if not files:
        print("check_format: no Ruby or JSON files to check.")
        return 0

    tmp = None
    base_dir = ROOT
    if args.staged:
        # Check the staged contents, which may differ from the working tree.
        tmp = tempfile.mkdtemp(prefix="check_format.")
        subprocess.run(["git", "checkout-index", "--prefix=" + tmp + "/", "--"] + sorted(files),
                       cwd=ROOT, check=True)
        base_dir = tmp
    try:
        problems = check_files(files, base_dir, args)
    finally:
        if tmp:
            shutil.rmtree(tmp, ignore_errors=True)

    if problems < 0:
        return 2
    if problems:
        print("\ncheck_format: %d problem%s found." % (problems, "" if problems == 1 else "s"))
        if not args.fix:
            print("Run `make format` (or `python3 tools/scripts/check_format.py --fix ...`) to fix "
                  "what can be fixed automatically.")
        return 1
    print("check_format: %d file%s OK." % (len(files), "" if len(files) == 1 else "s"))
    return 0


def check_files(files, base_dir, args):
    """Checks (or fixes) the collected files.

    @param files a dict of path => changed lines
    @param base_dir the folder holding the contents to check
    @param args the parsed command line
    @return the number of problems left, or -1 if a tool is missing
    """
    problems = 0
    for path in sorted(p for p in files if is_json(p)):
        message, fixed = check_json(path, read(base_dir, path))
        if message and fixed is not None and args.fix:
            write(path, fixed)
            print("Fixed %s" % path)
        elif message:
            print(message)
            problems += 1

    ruby = sorted(p for p in files if is_ruby(p))
    if not ruby:
        return problems
    rubocop = rubocop_command()
    if rubocop is None:
        msg = "RuboCop isn't installed (run `bundle install` or `gem install rubocop`)"
        if args.allow_missing_rubocop:
            print("check_format: warning: %s; Ruby files were not checked." % msg)
            return problems
        print("check_format: %s." % msg)
        return -1

    if args.fix:
        fix_ruby(rubocop, ruby, files)
        # The fixes move lines around: find the changed lines again.
        files = dict(files, **{p: lines for p, lines in collect(args).items() if p in files})
    report = run_rubocop(rubocop, ruby, base_dir)
    for path in ruby:
        for offense in report.get(path, []):
            if relevant(offense, files[path]):
                print(format_offense(path, offense))
                problems += 1
    return problems


def fix_ruby(rubocop, ruby, files):
    """Applies RuboCop's corrections to the changed lines of Ruby files.

    @param rubocop the command from rubocop_command()
    @param ruby the Ruby files (relative to the repository root)
    @param files a dict of path => changed lines
    """
    tmp = tempfile.mkdtemp(prefix="check_format.fix.")
    try:
        for path in ruby:
            os.makedirs(os.path.dirname(os.path.join(tmp, path)), exist_ok=True)
            shutil.copyfile(os.path.join(ROOT, path), os.path.join(tmp, path))
        run_rubocop(rubocop, ruby, tmp, autocorrect=True)
        for path in ruby:
            original = read(ROOT, path)
            merged = merge_fixes(original, read(tmp, path), files[path])
            if merged != original:
                write(path, merged)
                print("Fixed %s" % path)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


if __name__ == "__main__":
    sys.exit(main())
